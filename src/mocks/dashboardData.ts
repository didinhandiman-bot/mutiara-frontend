export const hitungKeberterimaan = (
  jumlahKasus: number,
  jumlahSmkhp: number
): number => {
  if (jumlahSmkhp <= 0) return 0;
  const rate = (1 - jumlahKasus / jumlahSmkhp) * 100;
  return Math.round(rate * 100) / 100;
};

